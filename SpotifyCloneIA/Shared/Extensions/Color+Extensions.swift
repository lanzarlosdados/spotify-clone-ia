import SwiftUI

// MARK: - Color Extensions
/// Centralized color definitions for the Spotify Clone app.
/// This extension provides easy access to custom colors used throughout the UI.
extension Color {
    
    /// The primary background color for most screens.
    static let primaryBackground = Color(red: 18/255, green: 18/255, blue: 18/255)
    
    /// A slightly lighter background for card components.
    static let cardBackground = Color(red: 41/255, green: 41/255, blue: 41/255)
}
